export type Language = 'bn' | 'en';

export type ResidentialKey = 'boarding' | 'non_residential' | 'day_care';

export const RESIDENTIAL_OPTIONS: {
  key: ResidentialKey;
  bn: 'আবাসিক (বোর্ডিং)' | 'অনাবাসিক' | 'ডে কেয়ার';
  en: string;
}[] = [
  { key: 'boarding', bn: 'আবাসিক (বোর্ডিং)', en: 'Residential (Boarding)' },
  { key: 'non_residential', bn: 'অনাবাসিক', en: 'Non-Residential' },
  { key: 'day_care', bn: 'ডে কেয়ার', en: 'Day Care' },
];

export function getResidentialLabel(key: ResidentialKey, lang: Language): string {
  const found = RESIDENTIAL_OPTIONS.find((item) => item.key === key);
  if (!found) return key;
  return lang === 'en' ? found.en : found.bn;
}

export function formatDigits(input: string | number, lang: Language): string {
  const bengaliDigits = ['০', '১', '২', '৩', '৪', '৫', '৬', '৭', '৮', '৯'];
  if (lang === 'bn') {
    return String(input).replace(/\d/g, (d) => bengaliDigits[Number(d)] ?? d);
  }
  const bnToEn: Record<string, string> = {
    '০': '0',
    '১': '1',
    '২': '2',
    '৩': '3',
    '৪': '4',
    '৫': '5',
    '৬': '6',
    '৭': '7',
    '৮': '8',
    '৯': '9',
  };
  return String(input).replace(/[০-৯]/g, (ch) => bnToEn[ch] ?? ch);
}

export function getLocalizedFormattedDates(lang: Language): {
  weekday: string;
  gregorian: string;
  hijri: string;
} {
  const now = new Date();
  const locale = lang === 'en' ? 'en-US' : 'bn-BD';
  let weekday = '';
  let gregorian = '';
  let hijri = '';

  try {
    weekday = new Intl.DateTimeFormat(locale, { weekday: 'long' }).format(now);
    gregorian = new Intl.DateTimeFormat(locale, {
      day: 'numeric',
      month: 'long',
      year: 'numeric',
    }).format(now);
  } catch {
    weekday = lang === 'en' ? 'Tuesday' : 'মঙ্গলবার';
    gregorian = now.toLocaleDateString(lang === 'en' ? 'en-US' : 'en-GB');
  }

  try {
    const hijriLocale =
      lang === 'en' ? 'en-US-u-ca-islamic-umalqura' : 'bn-BD-u-ca-islamic-umalqura';
    hijri = new Intl.DateTimeFormat(hijriLocale, {
      day: 'numeric',
      month: 'long',
      year: 'numeric',
    }).format(now);
  } catch {
    hijri = lang === 'en' ? 'Jumada al-Thani 1448 AH' : 'জমাদিউস সানি ১৪৪৮ হিজরি';
  }

  return { weekday, gregorian, hijri };
}

