const BENGALI_DIGITS = ['০', '১', '২', '৩', '৪', '৫', '৬', '৭', '৮', '৯'];

export function toBengaliDigits(input: string | number): string {
  return String(input).replace(/\d/g, (digit) => BENGALI_DIGITS[Number(digit)] ?? digit);
}

const BENGALI_WEEKDAYS = [
  'রবিবার',
  'সোমবার',
  'মঙ্গলবার',
  'বুধবার',
  'বৃহস্পতিবার',
  'শুক্রবার',
  'শনিবার',
];

export function getFormattedDates(): { weekday: string; gregorian: string; hijri: string } {
  const now = new Date();
  let weekday = BENGALI_WEEKDAYS[now.getDay()] ?? '';
  let gregorian = '';
  let hijri = '';

  try {
    weekday = new Intl.DateTimeFormat('bn-BD', { weekday: 'long' }).format(now);
    gregorian = new Intl.DateTimeFormat('bn-BD', {
      day: 'numeric',
      month: 'long',
      year: 'numeric',
    }).format(now);
  } catch {
    gregorian = toBengaliDigits(now.toLocaleDateString('en-GB'));
  }

  try {
    hijri = new Intl.DateTimeFormat('bn-BD-u-ca-islamic-umalqura', {
      day: 'numeric',
      month: 'long',
      year: 'numeric',
    }).format(now);
  } catch {
    hijri = 'জমাদিউস সানি ১৪৪৮ হিজরি';
  }

  return { weekday, gregorian, hijri };
}

export function generateTrackingId(): string {
  const randomDigits = Math.floor(1000 + Math.random() * 9000);
  return `ADM-2026-${randomDigits}`;
}
